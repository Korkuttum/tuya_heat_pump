# U-Energy LVI DC Inverter Heat Pump PW050 18KW (model PW58387)
# @norrgardstaffan-lab (issue #100)
# Reporter's own nameplate/whitelabel reference was "E0SWS0" -- NOT the
# same device as the e0sws0.py model elsewhere in this repo (that one
# is NMT MIA13, issue #97). This device's real Tuya modelId, confirmed
# from its own tuya_api_test.py dump, is e9mdpo -- a completely
# different DP layout, no relation to e0sws0.
#
# All the SENSOR_TYPES/SWITCH_TYPES/SELECT_TYPES below are confirmed
# straight from this device's own Tuya typeSpec (standard typed DPs,
# not raw) -- a much simpler layout than most contributed models, every
# important telemetry reading is its own plain DP.
#
# The writable settings (DHW/heating/cooling setpoints and the
# installer/engineer menu) all live inside parameter_group_1/2/7 (dp
# 118/119/124, raw, rw, "20 parameters x 4 bytes" per Tuya's own
# schema note) -- NUMBER_TYPES below were built and verified by
# @norrgardstaffan-lab with raw_explorer.py (changed each setting in
# the vendor app one at a time, confirmed which field moved). Several
# have no min/max because they're small enums (e.g. "Off/Automatic/
# Manual", "disable/enable") rather than a continuous range -- exposed
# as plain numbers (the raw integer the app itself uses), not guessed
# SELECT option labels, since the exact integer-to-label mapping for
# those wasn't confirmed.
#
# NOT included: reset (dp 125, "one-click reset to factory defaults").
# Exposing a factory-reset switch risks an accidental trigger; skipped
# deliberately rather than omitted by oversight.
#
# fault (dp 15) bitmap labels are bare "Er03".."Er70" codes with no
# description available from this report (no factory manual supplied,
# unlike fru9b0's) -- exposed as a raw bitmap + simple problem/no-
# problem binary sensor, same as other undocumented-fault models in
# this repo.

